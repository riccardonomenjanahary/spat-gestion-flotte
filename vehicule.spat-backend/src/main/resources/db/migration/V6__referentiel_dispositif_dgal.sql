-- =========================================================
-- 5. REPRISE DES CATEGORIES OFFICIELLES
-- =========================================================

DO $$
BEGIN
    IF to_regclass('public.vehicules') IS NOT NULL THEN

        -- 1205 TCA : patrouille et urgence
        UPDATE public.vehicules
        SET categorie = 'Véhicule de patrouille et d''urgence'
        WHERE REPLACE(immatriculation, ' ', '') ILIKE '1205TCA';

        -- 1614 / 1615 WWA : vehicules de mission
        UPDATE public.vehicules
        SET categorie = 'Véhicule de mission'
        WHERE REPLACE(immatriculation, ' ', '') ILIKE '01614WWA'
           OR REPLACE(immatriculation, ' ', '') ILIKE '01615WWA';

        -- 6 voitures de service mutualisees
        UPDATE public.vehicules
        SET categorie = 'Voiture de service mutualisée'
        WHERE REPLACE(immatriculation, ' ', '') IN (
            '5174AH', '6743AJ', '1218TCA',
            '6742AJ', '5533AE', '5334AJ'
        );

        -- Motos electriques : detention en leasing
        UPDATE public.vehicules
        SET mode_detention = 'LEASING'
        WHERE categorie ILIKE '%moto%';
    END IF;
END $$;


-- =========================================================
-- 6. GROUPES DE DIRECTIONS DES VOITURES MUTUALISEES
-- =========================================================
-- SG/DG        -> 5174 AH
-- DIREX/DMC    -> 6743 AJ
-- DFP/DIRCAP   -> 1218 TCA
-- DRH/DDI      -> 6742 AJ
-- DID/DAJ/DAGR -> 5533 AE et 5334 AJ
-- =========================================================

DO $$
BEGIN
    IF to_regclass('public.vehicules') IS NOT NULL THEN

        -- Nettoyage des liens precedents des vehicules du dispositif
        DELETE FROM public.vehicule_directions vd
        USING public.vehicules v
        WHERE vd.vehicule_id = v.id
          AND REPLACE(v.immatriculation, ' ', '') IN (
              '5174AH', '6743AJ', '1218TCA',
              '6742AJ', '5533AE', '5334AJ'
          );

        -- 5174 AH -> SG (11), DG (1)
        INSERT INTO public.vehicule_directions (vehicule_id, direction_id)
        SELECT v.id, d.id
        FROM public.vehicules v, public.directions d
        WHERE REPLACE(v.immatriculation, ' ', '') = '5174AH'
          AND d.code IN ('SG', 'DG')
        ON CONFLICT DO NOTHING;

        -- 6743 AJ -> DIREX (7), DMC (12)
        INSERT INTO public.vehicule_directions (vehicule_id, direction_id)
        SELECT v.id, d.id
        FROM public.vehicules v, public.directions d
        WHERE REPLACE(v.immatriculation, ' ', '') = '6743AJ'
          AND d.code IN ('DIREX', 'DMC')
        ON CONFLICT DO NOTHING;

        -- 1218 TCA -> DFP (8), DIRCAP (4)
        INSERT INTO public.vehicule_directions (vehicule_id, direction_id)
        SELECT v.id, d.id
        FROM public.vehicules v, public.directions d
        WHERE REPLACE(v.immatriculation, ' ', '') = '1218TCA'
          AND d.code IN ('DFP', 'DIRCAP')
        ON CONFLICT DO NOTHING;

        -- 6742 AJ -> DRH (9), DDI (10)
        INSERT INTO public.vehicule_directions (vehicule_id, direction_id)
        SELECT v.id, d.id
        FROM public.vehicules v, public.directions d
        WHERE REPLACE(v.immatriculation, ' ', '') = '6742AJ'
          AND d.code IN ('DRH', 'DDI')
        ON CONFLICT DO NOTHING;

        -- 5533 AE -> DID (5), DAJ (3), DAGR (13)
        INSERT INTO public.vehicule_directions (vehicule_id, direction_id)
        SELECT v.id, d.id
        FROM public.vehicules v, public.directions d
        WHERE REPLACE(v.immatriculation, ' ', '') = '5533AE'
          AND d.code IN ('DID', 'DAJ', 'DAGR')
        ON CONFLICT DO NOTHING;

        -- 5334 AJ -> DID (5), DAJ (3), DAGR (13)
        INSERT INTO public.vehicule_directions (vehicule_id, direction_id)
        SELECT v.id, d.id
        FROM public.vehicules v, public.directions d
        WHERE REPLACE(v.immatriculation, ' ', '') = '5334AJ'
          AND d.code IN ('DID', 'DAJ', 'DAGR')
        ON CONFLICT DO NOTHING;

        -- Synchronisation du texte d affectation (affichage historique)
        UPDATE public.vehicules SET affectation = 'SG, DG'
        WHERE REPLACE(immatriculation, ' ', '') = '5174AH';
        UPDATE public.vehicules SET affectation = 'DIREX, DMC'
        WHERE REPLACE(immatriculation, ' ', '') = '6743AJ';
        UPDATE public.vehicules SET affectation = 'DFP, DIRCAP'
        WHERE REPLACE(immatriculation, ' ', '') = '1218TCA';
        UPDATE public.vehicules SET affectation = 'DRH, DDI'
        WHERE REPLACE(immatriculation, ' ', '') = '6742AJ';
        UPDATE public.vehicules SET affectation = 'DID, DAJ, DAGR'
        WHERE REPLACE(immatriculation, ' ', '') IN ('5533AE', '5334AJ');
    END IF;
END $$;


