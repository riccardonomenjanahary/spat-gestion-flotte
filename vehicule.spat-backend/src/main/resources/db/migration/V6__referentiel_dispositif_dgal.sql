-- =========================================================
-- DISPOSITIF DGAL - REFERENTIEL CATEGORIES / DIRECTIONS
-- =========================================================
-- Traduit dans l'outil GPA les categories officielles
-- du dispositif d'utilisation des vehicules :
--
--   - Vehicule de patrouille et d'urgence (1205 TCA)
--   - Vehicules de mission (1614 WWA, 1615 WWA)
--   - Voitures de service mutualisees (6 vehicules par
--     groupe de Directions)
--   - Motos electriques (une par Direction, hors DG)
--
-- La migration est defensive : elle s'execute aussi bien
-- sur une base deja initialisee que sur une base vide
-- (Hibernate cree alors les colonnes manquantes apres
-- l'execution de Flyway).
-- =========================================================


-- =========================================================
-- 1. TABLE directions
-- =========================================================

CREATE TABLE IF NOT EXISTS public.directions (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code    VARCHAR(30)  NOT NULL,
    nom     VARCHAR(150) NOT NULL,
    actif   BOOLEAN      NOT NULL DEFAULT TRUE
);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'directions_code_key'
    ) THEN
        ALTER TABLE public.directions
            ADD CONSTRAINT directions_code_key UNIQUE (code);
    END IF;
END $$;


-- =========================================================
-- 2. TABLE vehicule_directions (groupe d'affectation)
-- =========================================================

CREATE TABLE IF NOT EXISTS public.vehicule_directions (
    vehicule_id  BIGINT NOT NULL,
    direction_id BIGINT NOT NULL,
    PRIMARY KEY (vehicule_id, direction_id)
);

DO $$
BEGIN
    IF to_regclass('public.vehicules') IS NOT NULL
       AND NOT EXISTS (
            SELECT 1 FROM pg_constraint
            WHERE conname = 'vehicule_directions_vehicule_fk'
       ) THEN
        ALTER TABLE public.vehicule_directions
            ADD CONSTRAINT vehicule_directions_vehicule_fk
            FOREIGN KEY (vehicule_id) REFERENCES public.vehicules(id);
    END IF;

    IF to_regclass('public.directions') IS NOT NULL
       AND NOT EXISTS (
            SELECT 1 FROM pg_constraint
            WHERE conname = 'vehicule_directions_direction_fk'
       ) THEN
        ALTER TABLE public.vehicule_directions
            ADD CONSTRAINT vehicule_directions_direction_fk
            FOREIGN KEY (direction_id) REFERENCES public.directions(id);
    END IF;
END $$;


-- =========================================================
-- 3. NOUVELLES COLONNES vehicules
-- =========================================================

DO $$
BEGIN
    IF to_regclass('public.vehicules') IS NOT NULL
       AND NOT EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_schema = 'public'
              AND table_name = 'vehicules'
              AND column_name = 'mode_detention'
       ) THEN
        ALTER TABLE public.vehicules
            ADD COLUMN mode_detention VARCHAR(30);
    END IF;

    IF to_regclass('public.vehicules') IS NOT NULL
       AND NOT EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_schema = 'public'
              AND table_name = 'vehicules'
              AND column_name = 'date_expiration_visite_technique'
       ) THEN
        ALTER TABLE public.vehicules
            ADD COLUMN date_expiration_visite_technique DATE;
    END IF;
END $$;


