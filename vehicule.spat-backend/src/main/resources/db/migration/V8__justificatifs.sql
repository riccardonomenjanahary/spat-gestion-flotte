-- =========================================================
-- DISPOSITIF DGAL - JUSTIFICATIFS DOCUMENTAIRES
-- =========================================================
-- Table de suivi des pièces du dispositif :
--
--   - ordre de mission signé (rattaché à une réservation)
--   - reçu de carburant / recharge (rattaché à une
--     transaction)
--   - documents du véhicule (carte grise, visite
--     technique, assurance, ...)
--
-- Migration défensive : s'exécute aussi bien sur une
-- base déjà initialisée que sur une base vide (Hibernate
-- créant alors les colonnes manquantes après Flyway).
-- =========================================================

-- =========================================================
-- 1. TABLE justificatifs
-- =========================================================

CREATE TABLE IF NOT EXISTS public.justificatifs (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type                     VARCHAR(40)  NOT NULL,
    nom_fichier              VARCHAR(260) NOT NULL,
    nom_stocke               VARCHAR(100) NOT NULL,
    taille_octets            BIGINT       NOT NULL,
    content_type             VARCHAR(150) NOT NULL,
    vehicule_id              BIGINT,
    reservation_id           BIGINT,
    transaction_carburant_id UUID,
    depose_par_id            BIGINT       NOT NULL,
    date_depot               TIMESTAMP    NOT NULL,
    valide                   BOOLEAN      NOT NULL DEFAULT FALSE,
    valide_par_id            BIGINT,
    date_validation          TIMESTAMP,
    commentaire_validation   VARCHAR(500),
    libelle                  VARCHAR(300)
);

-- =========================================================
-- 2. CLES ETRANGERES (uniquement si les tables cibles
--    existent déjà à l'exécution de Flyway)
-- =========================================================

DO $$
BEGIN
    IF to_regclass('public.justificatifs') IS NOT NULL
       AND to_regclass('public.vehicules') IS NOT NULL
       AND NOT EXISTS (
            SELECT 1 FROM pg_constraint
            WHERE conname = 'justificatifs_vehicule_fk'
       ) THEN
        ALTER TABLE public.justificatifs
            ADD CONSTRAINT justificatifs_vehicule_fk
            FOREIGN KEY (vehicule_id) REFERENCES public.vehicules(id);
    END IF;

    IF to_regclass('public.justificatifs') IS NOT NULL
       AND to_regclass('public.reservations') IS NOT NULL
       AND NOT EXISTS (
            SELECT 1 FROM pg_constraint
            WHERE conname = 'justificatifs_reservation_fk'
       ) THEN
        ALTER TABLE public.justificatifs
            ADD CONSTRAINT justificatifs_reservation_fk
            FOREIGN KEY (reservation_id) REFERENCES public.reservations(id);
    END IF;

    IF to_regclass('public.justificatifs') IS NOT NULL
       AND to_regclass('public.transactions_carburant') IS NOT NULL
       AND NOT EXISTS (
            SELECT 1 FROM pg_constraint
            WHERE conname = 'justificatifs_transaction_fk'
       ) THEN
        ALTER TABLE public.justificatifs
            ADD CONSTRAINT justificatifs_transaction_fk
            FOREIGN KEY (transaction_carburant_id)
            REFERENCES public.transactions_carburant(id);
    END IF;

    IF to_regclass('public.justificatifs') IS NOT NULL
       AND to_regclass('public.utilisateurs') IS NOT NULL
       AND NOT EXISTS (
            SELECT 1 FROM pg_constraint
            WHERE conname = 'justificatifs_depose_par_fk'
       ) THEN
        ALTER TABLE public.justificatifs
            ADD CONSTRAINT justificatifs_depose_par_fk
            FOREIGN KEY (depose_par_id) REFERENCES public.utilisateurs(id);
    END IF;

    IF to_regclass('public.justificatifs') IS NOT NULL
       AND to_regclass('public.utilisateurs') IS NOT NULL
       AND NOT EXISTS (
            SELECT 1 FROM pg_constraint
            WHERE conname = 'justificatifs_valide_par_fk'
       ) THEN
        ALTER TABLE public.justificatifs
            ADD CONSTRAINT justificatifs_valide_par_fk
            FOREIGN KEY (valide_par_id) REFERENCES public.utilisateurs(id);
    END IF;
END $$;

-- =========================================================
-- 3. INDEX DE CONSULTATION
-- =========================================================

CREATE INDEX IF NOT EXISTS justificatifs_vehicule_idx
    ON public.justificatifs (vehicule_id);

CREATE INDEX IF NOT EXISTS justificatifs_reservation_idx
    ON public.justificatifs (reservation_id);

CREATE INDEX IF NOT EXISTS justificatifs_transaction_idx
    ON public.justificatifs (transaction_carburant_id);
